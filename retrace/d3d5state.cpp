static void
dumpViewport(StateWriter &writer, IDirect3DDevice2 *pDevice)
{
    writer.beginMember("Viewport");
    writer.beginObject();

    IDirect3DViewport2 *vp2 = nullptr;
    HRESULT hr = pDevice->GetCurrentViewport(&vp2);
    if (SUCCEEDED(hr) && vp2) {
        D3DVIEWPORT vp;
        ZeroMemory(&vp, sizeof(vp));
        vp.dwSize = sizeof(vp);
        hr = vp2->GetViewport(&vp);
        if (SUCCEEDED(hr)) {
            writer.writeIntMember("X", vp.dwX);
            writer.writeIntMember("Y", vp.dwY);
            writer.writeIntMember("Width", vp.dwWidth);
            writer.writeIntMember("Height", vp.dwHeight);
            writer.writeFloatMember("MinZ", vp.dvMinZ);
            writer.writeFloatMember("MaxZ", vp.dvMaxZ);
        }
    }

    writer.endObject();
    writer.endMember();
}

